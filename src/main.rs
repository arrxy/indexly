fn main() -> io::Result<()> {
    let Some(options) = parse_options()? else {
        return Ok(());
    };

    if !Path::new(&options.dataset).is_file() {
        return Err(io::Error::new(
            io::ErrorKind::NotFound,
            "Dataset file not found",
        ));
    }

    // A new directory prevents stale runs from entering this index.
    if let Some(parent) = options.output.parent() {
        if !parent.as_os_str().is_empty() {
            fs::create_dir_all(parent)?;
        }
    }
    fs::create_dir(&options.output).map_err(|error| {
        if error.kind() == io::ErrorKind::AlreadyExists {
            invalid("Output directory already exists; choose a new --output directory")
        } else {
            error
        }
    })?;

    let work = options.output.join("_work");
    fs::create_dir(&work)?;
    let work_str = work
        .to_str()
        .ok_or_else(|| invalid("Output path must be UTF-8"))?;
    let total_start = Instant::now();

    let stage = Instant::now();
    let run_count = indexer::build_runs(
        &options.dataset,
        work_str,
        options.batch_bytes,
        &tokenizer::SimpleTokenizer,
    )?;
    println!(
        "Build: {run_count} runs in {:.2}s",
        stage.elapsed().as_secs_f64()
    );

    // Use exactly the files generated by this indexing pass.
    let runs: Vec<PathBuf> = (1..=run_count)
        .map(|number| work.join(format!("run_{number:04}.bin")))
        .collect();

    let stage = Instant::now();
    let merged = merge_all(runs, &work, options.merge_fan_in, options.keep_intermediate)?;
    println!("Merge: {:.2}s", stage.elapsed().as_secs_f64());

    let stage = Instant::now();
    let term_count = indexer::write_index(
        &merged,
        &options.output,
        options.block_size,
        &compression::Simple9,
    )?;
    fs::copy(
        work.join("page_table.bin"),
        options.output.join("page_table.bin"),
    )?;
    println!(
        "Compress: {term_count} terms in {:.2}s",
        stage.elapsed().as_secs_f64()
    );

    // Only remove temporary files created inside this new output directory.
    if !options.keep_intermediate {
        fs::remove_dir_all(&work)?;
    }

    println!("Index: {}", options.output.display());
    println!("Total: {:.2}s", total_start.elapsed().as_secs_f64());
    Ok(())
}

fn merge_all(
    mut runs: Vec<PathBuf>,
    work: &Path,
    fan_in: usize,
    keep_intermediate: bool,
) -> io::Result<PathBuf> {
    if runs.is_empty() {
        let empty = work.join("empty.bin");
        File::create(&empty)?;
        return Ok(empty);
    }

    let mut pass = 0;
    while runs.len() > 1 {
        pass += 1;
        let directory = work.join(format!("pass_{pass:03}"));
        fs::create_dir(&directory)?;
        let mut next = Vec::new();

        for (number, group) in runs.chunks(fan_in).enumerate() {
            if group.len() == 1 {
                next.push(group[0].clone());
                continue;
            }

            let output = directory.join(format!("run_{:04}.bin", number + 1));
            merger::merge_runs(group, &output)?;
            next.push(output);

            // This group's replacement was written successfully.
            if !keep_intermediate {
                for input in group {
                    fs::remove_file(input)?;
                }
            }
        }

        println!(
            "Merge pass {pass}: {} inputs -> {} outputs",
            runs.len(),
            next.len()
        );
        runs = next;
    }

    Ok(runs.pop().unwrap())
}

fn parse_options() -> io::Result<Option<Options>> {
    let mut args = std::env::args().skip(1);
    let mut dataset = None;
    let mut output = PathBuf::from("./output/index");
    let mut batch_bytes = 64 * 1024;
    let mut block_size = 128;
    let mut merge_fan_in = 64;
    let mut keep_intermediate = false;

    while let Some(arg) = args.next() {
        match arg.as_str() {
            "--help" | "-h" => {
                print!("{HELP}");
                return Ok(None);
            }
            "--output" => output = PathBuf::from(next_value(&mut args, "--output")?),
            "--batch-bytes" => batch_bytes = positive_number(&mut args, "--batch-bytes")?,
            "--block-size" => block_size = positive_number(&mut args, "--block-size")?,
            "--merge-fan-in" => merge_fan_in = positive_number(&mut args, "--merge-fan-in")?,
            "--keep-intermediate" => keep_intermediate = true,
            _ if arg.starts_with('-') => return Err(invalid(format!("Unknown option: {arg}"))),
            _ => {
                if dataset.replace(arg).is_some() {
                    return Err(invalid("Provide exactly one dataset filename"));
                }
            }
        }
    }

    let dataset = dataset.ok_or_else(|| invalid(HELP))?;
    if merge_fan_in < 2 {
        return Err(invalid("--merge-fan-in must be at least 2"));
    }
    if u32::try_from(block_size).is_err() {
        return Err(invalid("--block-size exceeds u32"));
    }

    Ok(Some(Options {
        dataset,
        output,
        batch_bytes,
        block_size,
        merge_fan_in,
        keep_intermediate,
    }))
}

fn next_value(args: &mut impl Iterator<Item = String>, flag: &str) -> io::Result<String> {
    args.next()
        .ok_or_else(|| invalid(format!("Missing value for {flag}")))
}

fn positive_number(args: &mut impl Iterator<Item = String>, flag: &str) -> io::Result<usize> {
    let value = next_value(args, flag)?;
    let number = value
        .parse::<usize>()
        .map_err(|_| invalid(format!("Invalid value for {flag}: {value}")))?;
    if number == 0 {
        return Err(invalid(format!("{flag} must be greater than zero")));
    }
    Ok(number)
}

fn invalid(message: impl Into<String>) -> io::Error {
    io::Error::new(io::ErrorKind::InvalidInput, message.into())
}
